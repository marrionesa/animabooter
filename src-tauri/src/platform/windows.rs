fn werr(e: windows::core::Error) -> AppError {
    AppError::Device {
        message: format!("Win32 error: {e}"),
        hint: Some("Close any window or program using the drive and try again.".to_string()),
    }
}

fn io_err(e: io::Error) -> AppError {
    AppError::Device {
        message: format!("device I/O error: {e}"),
        hint: Some(crate::safety::HINT_UNKNOWN_STATE.to_string()),
    }
}

/// Open a Win32 path (volume or PhysicalDrive) with the given access.
fn open_path(path: &str, read: bool, write: bool, no_buffering: bool) -> Result<HANDLE, AppError> {
    let wide = HSTRING::from(path);
    let mut access = 0u32;
    if read {
        access |= GENERIC_READ.0;
    }
    if write {
        access |= GENERIC_WRITE.0;
    }
    let flags = if no_buffering {
        FILE_FLAG_NO_BUFFERING
    } else {
        Default::default()
    };
    unsafe {
        CreateFileW(
            PCWSTR(wide.as_ptr()),
            access,
            FILE_SHARE_READ | FILE_SHARE_WRITE,
            None,
            OPEN_EXISTING,
            flags,
            None,
        )
        .map_err(werr)
    }
}

/// DeviceIoControl with manual buffers (bounded, bounds-checked parsing).
fn ioctl(
    handle: HANDLE,
    code: u32,
    input: Option<(*const u8, u32)>,
    output: Option<(*mut u8, u32)>,
) -> Result<(), AppError> {
    let mut returned = 0u32;
    let (in_ptr, in_len) = match input {
        Some((p, l)) => (Some(p.cast()), l),
        None => (None, 0),
    };
    let (out_ptr, out_len) = match output {
        Some((p, l)) => (Some(p.cast()), l),
        None => (None, 0),
    };
    unsafe {
        DeviceIoControl(
            handle,
            code,
            in_ptr,
            in_len,
            out_ptr,
            out_len,
            Some(&mut returned),
            None,
        )
    }
    .map_err(werr)
}

fn u32_at(buf: &[u8], offset: usize) -> Option<u32> {
    if offset + 4 <= buf.len() {
        Some(u32::from_le_bytes([
            buf[offset],
            buf[offset + 1],
            buf[offset + 2],
            buf[offset + 3],
        ]))
    } else {
        None
    }
}

fn cstr_at(buf: &[u8], offset: u32) -> String {
    let start = offset as usize;
    if start == 0 || start >= buf.len() {
        return String::new();
    }
    let end = buf[start..]
        .iter()
        .position(|&c| c == 0)
        .map(|p| start + p)
        .unwrap_or(buf.len());
    String::from_utf8_lossy(&buf[start..end]).trim().to_string()
}

