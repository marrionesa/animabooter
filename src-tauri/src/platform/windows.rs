//! Windows backend — the meticulous one.
//!
//! * Elevation: `GetTokenInformation(TokenElevation)`; without admin, `flash`
//!   fails with a hint and the UI offers "Restart as admin" (PowerShell
//!   `Start-Process -Verb RunAs` with the `--elevated` flag).
//! * Enumeration: drive letters → volume handles →
//!   `IOCTL_STORAGE_GET_DEVICE_NUMBER` → PhysicalDrive number; disk metadata
//!   via `IOCTL_STORAGE_QUERY_PROPERTY` (vendor/product/serial/removable/bus)
//!   and `IOCTL_DISK_GET_LENGTH_INFO` for the size.
//! * Writing: `\\.\PhysicalDrive{n}` opened with
//!   `FILE_FLAG_NO_BUFFERING` → buffers and lengths are ALIGNED to the
//!   sector reported by `IOCTL_DISK_GET_DRIVE_GEOMETRY` (fallback 512).
//!   Every volume of the disk is locked + dismounted before the first write.
//! * Ejection: `IOCTL_STORAGE_EJECT_MEDIA` on the PhysicalDrive handle.
//!
//! Implementation note: small Win32 output structs (STORAGE_DEVICE_NUMBER,
//! GET_LENGTH_INFORMATION, DISK_GEOMETRY, STORAGE_DEVICE_DESCRIPTOR) are
//! parsed manually from byte buffers. This avoids depending on the exact
//! struct definitions generated by windows-rs and keeps every field access
//! bounds-checked.

